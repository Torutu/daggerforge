import esbuild from "esbuild";
import process from "process";
import { readFileSync } from "node:fs";
import { builtinModules } from "node:module";

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
If you want to view the source, please visit the GitHub repository of this plugin
*/`;

const prod = process.argv[2] === "production";

const nodeEnv = prod ? '"production"' : '"development"';

const context = await esbuild.context({
	banner: { js: banner },
	entryPoints: ["src/main.ts"],
	bundle: true,
	external: [
		"obsidian",
		"electron",
		"@codemirror/autocomplete",
		"@codemirror/collab",
		"@codemirror/commands",
		"@codemirror/language",
		"@codemirror/lint",
		"@codemirror/search",
		"@codemirror/state",
		"@codemirror/view",
		"@lezer/common",
		"@lezer/highlight",
		"@lezer/lr",
		...builtinModules,
	],
	jsx: "automatic",
	jsxImportSource: "preact",
	// The UI runs on Preact through its React-compatible API, so the source
	// keeps importing "react" / "react-dom/client". react-dom ships code that
	// creates <script> elements at runtime, which Obsidian's plugin review
	// rejects; Preact has no such code.
	alias: {
		"react": "preact/compat",
		"react-dom": "preact/compat",
	},
	format: "cjs",
	target: "es2018",
	logLevel: "info",
	sourcemap: prod ? false : "inline",
	treeShaking: true,
	outfile: "main.js",
	minify: prod,
	define: {
		// Replace all process references at compile time so React works in Obsidian's
		// browser environment, which has no Node.js globals.
		"process.env.NODE_ENV": nodeEnv,
		"process.env":          JSON.stringify({ NODE_ENV: prod ? "production" : "development" }),
		"process":              JSON.stringify({ env: { NODE_ENV: prod ? "production" : "development" } }),
	},
});

// Fails the build (and so the release workflow) if any dependency ever brings
// runtime <script> element creation back into the bundle.
function assertNoScriptElementCreation(file) {
	const bundle = readFileSync(file, "utf8");
	if (/createElement\(\s*["'`]script["'`]\s*\)/.test(bundle)) {
		console.error(`${file} contains createElement("script") - a dependency creates <script> elements at runtime.`);
		process.exit(1);
	}
}

if (prod) {
	await context.rebuild();
	assertNoScriptElementCreation("main.js");
	process.exit(0);
} else {
	await context.watch();
}
